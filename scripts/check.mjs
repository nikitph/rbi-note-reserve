import {chromium} from 'playwright';
import {readFileSync,mkdirSync} from 'node:fs';
mkdirSync('work',{recursive:true});
import assert from 'node:assert/strict';
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const browser=await chromium.launch({headless:true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? {executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH} : {})});
const page=await browser.newPage({viewport:{width:1100,height:800},colorScheme:'light'});
const errors=[]; page.on('pageerror',e=>errors.push(String(e)));
page.on('console',m=>{if(['error','warning'].includes(m.type()))errors.push(m.text());});
await page.setContent(html); await page.waitForSelector('#loader svg path');
assert.equal(await page.locator('svg').count(),2);
assert.equal(await page.locator('#widget-read').textContent(),'rest');
const b=await page.locator('#widget svg').boundingBox();
await page.mouse.move(b.x+196/400*b.width,b.y+173/320*b.height);
await page.waitForTimeout(1000);
assert.equal(await page.locator('#widget-read').textContent(),'₹100 · 03');
await page.screenshot({path:'work/both-light.png'});
await page.mouse.move(10,10); await page.waitForTimeout(1000);
assert.equal(await page.locator('#widget-read').textContent(),'rest');
await page.locator('#intensity').fill('1');
assert.equal(await page.locator('#intensity-value').textContent(),'100%');
async function countAt(speed) {
 await page.locator('#speed').fill(String(speed));
 const phases=new Set();
 for(let i=0;i<15;i++) {await page.waitForTimeout(100); phases.add(await page.locator('#loader').getAttribute('data-phase'));}
 return phases.size;
}
const slow=await countAt(.25), fast=await countAt(3);
assert(fast>slow,`speed changes real cadence: ${slow} vs ${fast}`);
assert.equal(await page.locator('#speed-value').textContent(),'3×');
assert.equal(await page.locator('#cycle').textContent(),'2.2 seconds per cycle.');
assert.equal(await page.locator('#widget-read').textContent(),'rest');
await page.getByRole('button',{name:'Switch colour theme'}).click();
await page.screenshot({path:'work/both-dark.png'});
await page.setViewportSize({width:390,height:1000});
await page.screenshot({path:'work/both-small.png',fullPage:true});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.setViewportSize({width:240,height:1000});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.goto('about:blank');
await page.emulateMedia({reducedMotion:'reduce'});
await page.setContent(html); await page.waitForSelector('#loader svg path');
await page.waitForTimeout(200);
const before=await page.locator('#loader svg').innerHTML();
await page.waitForTimeout(1000);
assert.equal(await page.locator('#loader svg').innerHTML(),before);
await page.evaluate(()=>{window.reserveWidget.destroy();window.reserveLoader.destroy();});
assert.equal(await page.locator('svg *').count(),0);
assert.deepEqual(errors,[]);
console.log(`PASS: both figures render; hover selects 03 and leaving returns to rest; intensity works; speed changes cadence (${slow} vs ${fast} phases / 1.5s); theme works; 390/240px fit; reduced motion static; both destroy cleanly; no console errors.`);
await browser.close();
